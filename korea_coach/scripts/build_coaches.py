def pack_rating(score, note, kind, style, shape, alt, values):
    if not 1 <= int(score) <= 100:
        raise ValueError(f"rating out of range: {score}")
    if len(values) != len(ATTR_LABELS):
        raise ValueError(f"expected {len(ATTR_LABELS)} attrs, got {len(values)}")
    for value in values:
        if not 1 <= int(value) <= 20:
            raise ValueError(f"ability out of range: {value}")
    return {
        "rating": int(score),
        "note": note,
        "tactics": {
            "kind": kind,
            "style": style,
            "shape": shape,
            "alt": alt,
        },
        "abilities": [
            {"label": label, "value": int(value)} for label, value in zip(ATTR_LABELS, values)
        ],
    }


def attach_axis(cid, pack):
    pair = AXIS.get(cid)
    if not pair:
        raise KeyError(f"missing attack/defense for {cid}")
    attack, defense = (int(pair[0]), int(pair[1]))
    for value in (attack, defense):
        if not 1 <= value <= 20:
            raise ValueError(f"axis out of range for {cid}: {value}")
    if attack - defense >= 3:
        tendency = "공격형"
    elif defense - attack >= 3:
        tendency = "수비형"
    else:
        tendency = "밸런스"
    abilities = [
        {"label": "공격", "value": attack},
        {"label": "수비", "value": defense},
    ] + list(pack["abilities"])
    return {
        **pack,
        "abilities": abilities,
        "axis": {"attack": attack, "defense": defense},
        "tendency": tendency,
    }


